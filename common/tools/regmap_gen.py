"""SKETCH: generate C++ register mask/reset constants from SystemRDL.

This is a *proposal sketch*, not yet part of the build. It closes the one
genuinely open gap between the in-house ``regmodel`` library and CSML: keeping
the per-register mask / reset constants in the C++ models in sync with the
ground-truth ``*.rdl`` spec, instead of hand-transcribing them from RDL comments
(the source of silent drift today).

It emits, per register, ``constexpr`` values that plug straight into
``reg_access.h`` / ``reg_map.h``:

    * ``<REG>_OFFSET``     byte offset (from the RDL address map)
    * ``<REG>_RESET``      reset value (assembled from field reset values)
    * ``<REG>_RMASK``      software-readable bit mask  (Register read_mask)
    * ``<REG>_WMASK``      software-writable bit mask  (Register write_mask)

so a model can write, drift-free::

    #include "uart_16550_main.regmap.gen.h"
    regmodel::Register8 scr{gen::uart::SCR_RMASK, gen::uart::SCR_WMASK, gen::uart::SCR_RESET};

The masks are *derived from the RDL field access types* (the same information a
CSML generator would use), so RO/WO/RW policy comes from the spec rather than a
hand-copied ``0x3F``.

------------------------------------------------------------------------------
Dependency (why it is not run in this repo yet):

    pip install systemrdl-compiler      # the standard PeakRDL front end

Usage:

    python3 common/tools/regmap_gen.py \
        --rdl path/to/uart_16550_main.rdl \
        --namespace gen::uart \
        --out smc/peripherals/uart/include/uart_16550_main.regmap.gen.h

What this sketch deliberately leaves out (would be the productionization work):
    * arrays / register files with strides (emit indexed helpers);
    * 64-bit registers split across 32-bit access (emit lane masks);
    * enum/field-level constants (only whole-register masks here);
    * a CMake custom command + a check mode that fails CI if the checked-in
      generated header is stale vs. the RDL.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

# --- header/footer helpers --------------------------------------------------


def _cpp_ns_open(ns: str) -> str:
    return "".join(f"namespace {p} {{ " for p in ns.split("::")) + "\n"


def _cpp_ns_close(ns: str) -> str:
    return "".join("} " for _ in ns.split("::")) + f"// namespace {ns}\n"


def _emit_header(ns: str, src: str, regs: list[dict]) -> str:
    out: list[str] = []
    out.append("// SPDX-License-Identifier: Apache-2.0")
    out.append("// AUTO-GENERATED by common/tools/regmap_gen.py -- DO NOT EDIT.")
    out.append(f"// Source RDL: {src}")
    out.append("//")
    out.append("// Regenerate:  python3 common/tools/regmap_gen.py --rdl <spec> ...")
    out.append("#pragma once")
    out.append("#include <cstdint>")
    out.append("")
    out.append(_cpp_ns_open(ns))
    for r in regs:
        w = r["width"]
        suffix = "u" if w <= 32 else "ull"
        out.append(f"// {r['name']}: {r['desc']}")
        out.append(f"inline constexpr uint64_t {r['name']}_OFFSET = 0x{r['offset']:X}{suffix};")
        out.append(f"inline constexpr uint{w}_t {r['name']}_RESET  = 0x{r['reset']:X}{suffix};")
        out.append(f"inline constexpr uint{w}_t {r['name']}_RMASK  = 0x{r['rmask']:X}{suffix};")
        out.append(f"inline constexpr uint{w}_t {r['name']}_WMASK  = 0x{r['wmask']:X}{suffix};")
        out.append("")
    out.append(_cpp_ns_close(ns))
    return "\n".join(out) + "\n"


# --- RDL extraction ---------------------------------------------------------


def _extract_registers(rdl_paths: list[str]) -> list[dict]:
    """Compile the RDL and pull whole-register offset/reset/masks out of it.

    Uses systemrdl-compiler (PeakRDL). Kept in one function so the rest of the
    script has no hard import dependency until it is actually invoked.
    """
    try:
        from systemrdl import RDLCompiler
        from systemrdl.node import AddrmapNode, RegNode
    except ImportError:
        sys.exit(
            "error: systemrdl-compiler not installed.\n"
            "       pip install systemrdl-compiler\n"
            "       (this script is a sketch; the dependency is intentional.)"
        )

    rdlc = RDLCompiler()
    for p in rdl_paths:
        rdlc.compile_file(p)
    root = rdlc.elaborate()

    regs: list[dict] = []

    def visit(node) -> None:
        for child in node.children():
            if isinstance(child, RegNode):
                _add_reg(child, regs)
            elif isinstance(child, AddrmapNode) or child.children():
                visit(child)

    visit(root.top)
    return regs


def _add_reg(reg, regs: list[dict]) -> None:
    width = reg.get_property("regwidth", default=32)
    reset = 0
    rmask = 0
    wmask = 0
    for f in reg.fields():
        lsb, msb = f.lsb, f.msb
        fmask = ((1 << (msb - lsb + 1)) - 1) << lsb
        if f.is_sw_readable:
            rmask |= fmask
        if f.is_sw_writable:
            wmask |= fmask
        fr = f.get_property("reset")
        if fr is not None:
            reset |= (int(fr) << lsb) & fmask

    regs.append(
        {
            "name": reg.inst_name.upper(),
            "desc": (reg.get_property("desc") or "").splitlines()[0][:70] if reg.get_property("desc") else "",
            "offset": reg.absolute_address,
            "reset": reset,
            "rmask": rmask,
            "wmask": wmask,
            "width": width,
        }
    )


# --- main -------------------------------------------------------------------


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--rdl", action="append", required=True,
                    help="RDL file(s); repeat for multiple (deps first).")
    ap.add_argument("--namespace", default="gen",
                    help="C++ namespace for the generated constants (e.g. gen::uart).")
    ap.add_argument("--out", type=Path, required=True, help="Output header path.")
    ap.add_argument("--check", action="store_true",
                    help="Fail (non-zero) if --out is missing or stale vs. the RDL.")
    args = ap.parse_args()

    regs = _extract_registers(args.rdl)
    if not regs:
        sys.exit("error: no registers found in the supplied RDL.")
    text = _emit_header(args.namespace, ",".join(args.rdl), regs)

    if args.check:
        current = args.out.read_text() if args.out.exists() else ""
        if current != text:
            sys.exit(f"error: {args.out} is stale vs. RDL; regenerate with regmap_gen.py")
        print(f"ok: {args.out} is up to date ({len(regs)} registers)")
        return 0

    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(text)
    print(f"wrote {args.out} ({len(regs)} registers from {len(args.rdl)} RDL file(s))")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
