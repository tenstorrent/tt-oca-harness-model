"""Generate test/inc/abr_signer_vectors.h: ML-DSA-87 signatures from an independent signer.

The model's ML-DSA math is PQClean. These vectors come from OpenSSL's ML-DSA through
Python `cryptography` (48 or later), so agreement between the two is a
cross-implementation check rather than PQClean verifying itself.

The key is derived from a fixed seed, so the public key is reproducible. Signing is
hedged (the API has no deterministic mode), so the signatures change on every run;
the tests depend only on whether they verify. Message lengths cover each final-word
strobe form of a streamed message (5900-5903 bytes) and the short and empty cases, and
three entries carry a context. Every signature is checked with the signer's own verify
before it is written.

Usage: gen_abr_signer_vectors.py   (needs cryptography >= 48)
"""

import os

from cryptography.hazmat.primitives import serialization
from cryptography.hazmat.primitives.asymmetric import mldsa

OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "inc", "abr_signer_vectors.h")

SEED = bytes(range(0x40, 0x60))

# (message length, context)
CASES = [
    (5903, b""),
    (5902, b""),
    (5901, b""),
    (5900, b""),
    (3, b""),
    (0, b""),
    (5903, bytes(range(21))),
    (3, b"ABR context"),
    (64, bytes((0xC0 + i) & 0xFF for i in range(255))),
]


def message(n):
    return bytes((i * 7 + 3) & 0xFF for i in range(n))


def c_bytes(name, data):
    out = [f"static const uint8_t {name}[{max(len(data), 1)}] = {{"]
    for i in range(0, len(data), 16):
        out.append("    " + " ".join(f"0x{b:02x}," for b in data[i : i + 16]))
    if not data:
        out.append("    0x00,")
    out.append("};")
    return out


def main():
    key = mldsa.MLDSA87PrivateKey.from_seed_bytes(SEED)
    pub = key.public_key()
    pk = pub.public_bytes(serialization.Encoding.Raw, serialization.PublicFormat.Raw)

    lines = [
        "// SPDX-License-Identifier: Apache-2.0",
        "// SPDX-FileCopyrightText: 2026 Tenstorrent USA, Inc.",
        "// Generated by test/scripts/gen_abr_signer_vectors.py. Do not edit.",
        "// ML-DSA-87 (FIPS 204 pure, hedged) signatures from OpenSSL via Python cryptography.",
        "",
        "#pragma once",
        "",
        "#include <cstddef>",
        "#include <cstdint>",
        "",
    ]
    lines += c_bytes("abr_signer_seed", SEED)
    lines += c_bytes("abr_signer_pk", pk)
    lines.append("")

    entries = []
    for idx, (mlen, ctx) in enumerate(CASES):
        msg = message(mlen)
        sig = key.sign(msg, ctx if ctx else None)
        pub.verify(sig, msg, ctx if ctx else None)
        lines += c_bytes(f"abr_signer_msg_{idx}", msg)
        lines += c_bytes(f"abr_signer_ctx_{idx}", ctx)
        lines += c_bytes(f"abr_signer_sig_{idx}", sig)
        lines.append("")
        entries.append((idx, mlen, len(ctx)))

    lines += [
        "struct abr_signer_case {",
        "    const uint8_t *msg;",
        "    std::size_t msg_len;",
        "    const uint8_t *ctx;",
        "    std::size_t ctx_len;",
        "    const uint8_t *sig;",
        "};",
        "",
        "static const abr_signer_case abr_signer_cases[] = {",
    ]
    for idx, mlen, clen in entries:
        lines.append(
            f"    {{abr_signer_msg_{idx}, {mlen}u, abr_signer_ctx_{idx}, {clen}u, abr_signer_sig_{idx}}},"
        )
    lines += ["};", ""]

    with open(OUT, "w", encoding="ascii") as f:
        f.write("\n".join(lines))
    print(f"wrote {len(entries)} signatures to {OUT}")


if __name__ == "__main__":
    main()
