/* simulates the encrypted of a message followed by a decryption.
   - Uses a public key for the encryption.
   - Uses a private key for the decryption.
   - Verifies the message decrypted message.
*/
int rsa_encrypt_decrypt_main(void)
{
   struct pka_state pka;
   struct pka_rsa_mod rsamod;
   struct pka_rsa_key key;
   uint8_t  *mem_block;
   uint8_t *ct;
   uint8_t *msg_decrypted;
   int i = 0;
   uint16_t  keysize;

   int err = PKA_ERR;
   int fail_count = 1;

   printf("Start encrypt decrypt Sample App\n");

   // Init pka instance
   memset(&pka, 0, sizeof(struct pka_state));

   keysize = n1_len ;

   // malloc  a block of memory with the size of all buffer needed
   err = (int)ALLOC_MEMBLOCK( mem_block , MEM_BLOCK_SIZE(keysize));
   if (err == 0)
   {
       printf("%s line %d malloc fail size=0x%x\n", __FUNCTION__, __LINE__, MEM_BLOCK_SIZE(keysize));
       free(mem_block);
       return PKA_ERR;
   }
   memset(mem_block, 0, MEM_BLOCK_SIZE(keysize));

   // point buffers to memory block
   RSA_MOD_M(mem_block,rsamod.m, keysize);
   RSA_MOD_RSQR(mem_block,rsamod.r_sqr, keysize);
   RSA_MOD_MP(mem_block,rsamod.mp, keysize);
   RSA_KEY_EXP(mem_block, key.exp, keysize);
   RSA_CT(mem_block,ct, keysize);
   RSA_MSGDECRYPT(mem_block,msg_decrypted, keysize);

   //Initialize and load firmware
   err = pka_lib_setup(&pka, PKA_BASE_ADDRESS, (uint8_t *)ram_fw_bin, ram_fw_bin_len);
   if (err != PKA_OK)
   {
      printf("%s line=%d err=%d\n", __FUNCTION__, __LINE__, err);
      goto DONE;
   }

   // Initialize public key
   key.mod_size = n1_len;
   key.n = rsamod;
   memcpy(key.exp, e1, n1_len);
   memcpy(rsamod.m, n1, n1_len);

   // precompute function to populate r_sqr and  mp
   err = pka_rsa_precomp(&pka, &rsamod, n1_len);
   if (err != PKA_OK)
   {
      printf("%s line=%d err=%d\n", __FUNCTION__, __LINE__, err);
      goto DONE;
   }

   err = pka_rsa_encrypt(&pka, &key, Msg1, Msg1_len, rng, rng_len, ct);
   if (err != PKA_OK)
   {
      printf("%s line=%d err=%d\n", __FUNCTION__, __LINE__, err);
      goto DONE;
   }

   // load private key for decrypt
   memcpy(key.exp, d1, n1_len );

   err = pka_rsa_decrypt(&pka, &key, RSA_KEY, ct, msg_decrypted, Msg1_len);
   if (err != PKA_OK)
   {
      printf("%s line=%d err=%d\n", __FUNCTION__, __LINE__, err);
      goto DONE;
   }

   // check message
   fail_count = 0;
   for (i=0; i < Msg1_len; i++)
   {
      if (Msg1[i] != msg_decrypted[i])
      {
         printf("FAIL i = 0x%x  Msg1 = 0x%x,  actual = 0x%x\n", i, Msg1[i], msg_decrypted[i]);
         fail_count++;
      }
   }
   if (fail_count == 0)
   {
      printf("Encryption/Decryption PASSED\n");
   }
   else
   {
      printf("Encryption/Decryption FAILED fail count=%d\n", fail_count);
   }

DONE:
   free(mem_block);

   err = pka_lib_close(&pka);
   if (err != PKA_OK)
   {
      printf("%s line=%d err=%d\n", __FUNCTION__, __LINE__, err);
      return err;
   }

   return ((err == PKA_OK) && (fail_count == 0)) ? 0 : 1;
}

