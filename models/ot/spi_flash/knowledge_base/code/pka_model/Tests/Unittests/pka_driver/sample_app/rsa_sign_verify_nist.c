/* simulates the sign and verify of a message.
   - Uses a private key for the creating the signature.
   - Uses a public key for verifying the signature.
*/
int rsa_sign_verify_nist_main(void)
{
   struct pka_state pka;
   struct pka_rsa_mod rsamod;
   struct pka_rsa_key key;

   int err = PKA_ERR;
   int pass_fail = 1;

   uint8_t  *mem_block;
   uint8_t  *signature;
   uint8_t  *hash;
   uint16_t  keysize;

   printf("Start sign verify nist Sample App\n");

   // Init pka instance
   memset(&pka, 0, sizeof(struct pka_state));

   keysize = n1_len ;

   // malloc  a block of memory with the size of all buffer needed
   err = (int)ALLOC_MEMBLOCK( mem_block , MEM_BLOCK_SIZE(keysize));
   if (err == 0)
   {
       printf("%s line %d malloc fail size=0x%x\n", __FUNCTION__, __LINE__, MEM_BLOCK_SIZE(keysize));
       free(mem_block);
       return  PKA_ERR;
   }
   memset(mem_block, 0, MEM_BLOCK_SIZE(keysize));

   // point buffers to memory block
   RSA_MOD_M(mem_block,rsamod.m, keysize);
   RSA_MOD_RSQR(mem_block,rsamod.r_sqr, keysize);
   RSA_MOD_MP(mem_block,rsamod.mp, keysize);
   RSA_KEY_EXP(mem_block, key.exp, keysize);
   RSA_SIG(mem_block,signature, keysize);
   RSA_HAS(mem_block,hash, keysize);

   //Initialize and load firmware
   err = pka_lib_setup(&pka, PKA_BASE_ADDRESS, (uint8_t *)ram_fw_bin, ram_fw_bin_len);
   if (err != PKA_OK)
   {
      printf("%s line=%d err=%d\n", __FUNCTION__, __LINE__, err);
      goto DONE;
   }

   // Initialize  private key
   key.mod_size = n1_len;
   key.n = rsamod;
   memcpy(key.exp, d1,n1_len);
   memcpy(rsamod.m,n1, n1_len);
   memcpy(hash, sha1, n1_len );

   // precompute function to populate r_sqr and  mp
   err = pka_rsa_precomp(&pka, &rsamod, n1_len);
   if (err != PKA_OK)
   {
      printf("%s line=%d err=%d\n", __FUNCTION__, __LINE__, err);
      goto DONE;
   }

   // sign sha1
   err = pka_rsa_sign(&pka, &key, RSA_KEY, hash, PKA_HASH_SHA512, signature);
   if (err != PKA_OK)
   {
      printf("%s line %d err=0x%x\n", __FUNCTION__, __LINE__, err);
      goto DONE;
   }

   //copy the public key to structure for verification
   memcpy(key.exp, e1, n1_len);

   // verify Signature
   err = pka_rsa_verify(&pka, &key, hash, PKA_HASH_SHA512, signature);

   if (err != PKA_OK)
   {
      printf("%s line=%d err=%d\n", __FUNCTION__, __LINE__, err);
   }
   else
   {
      printf("Sign and verify passed\n");
      pass_fail = 0;
   }

DONE:
   free(mem_block);

   err = pka_lib_close(&pka);
   if (err != PKA_OK)
   {
      printf("%s line=%d err=%d\n", __FUNCTION__, __LINE__, err);
      return err;
   }

   return pass_fail;
}

